package com.coraline.postgame;

import net.minecraft.core.*;
import net.minecraft.world.level.WorldGenLevel;
import net.minecraft.world.level.block.*;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.levelgen.structure.BoundingBox;

/** A two-storey residence with a grand stair, six side rooms on each floor,
 * an upper gallery, and the vault behind a false mirror wall. */
final class PorcelainMansionLayout {
    static void place(WorldGenLevel level,BoundingBox clip,InfiniteStructurePlan.Plan plan,int index){
        var room=plan.modules().get(index);if(plan.family()!=InfiniteStructurePlan.Family.PORCELAIN_MANSION||room.role()!=InfiniteStructurePlan.Role.MANSION_HALL)return;
        var o=new BlockPos(plan.x()+room.x(),plan.y()+room.y(),plan.z()+room.z());var wall=InfiniteContent.block("porcelain_stone").defaultBlockState();var tile=Blocks.SMOOTH_QUARTZ.defaultBlockState();
        for(int x=1;x<=21;x++)for(int z=1;z<=21;z++)if(!(x>=9&&x<=13&&z>=6&&z<=13))put(level,clip,o.offset(x,8,z),tile);
        for(int floor:new int[]{0,8}){
            for(int x:new int[]{7,15})for(int z=1;z<=21;z++)for(int y=1;y<=7;y++){
                boolean door=(Math.abs(z-4)<=1||Math.abs(z-11)<=1||Math.abs(z-18)<=1)&&y<=2;
                boolean hidden=floor==8&&x==15&&Math.abs(z-18)<=1&&y<=2;
                if(hidden)put(level,clip,o.offset(x,floor+y,z),InfiniteContent.ILLUSION_MIRROR.get().defaultBlockState());
                else if(!door)put(level,clip,o.offset(x,floor+y,z),wall);
            }
            for(int z:new int[]{7,15})for(int x=1;x<=21;x++)if(x<7||x>15)for(int y=1;y<=7;y++)put(level,clip,o.offset(x,floor+y,z),wall);
        }
        for(int step=0;step<8;step++)for(int x=10;x<=12;x++)put(level,clip,o.offset(x,step+1,step+6),Blocks.QUARTZ_STAIRS.defaultBlockState().setValue(StairBlock.FACING,Direction.SOUTH));
        for(int x:new int[]{8,14})for(int z=6;z<=12;z++)put(level,clip,o.offset(x,9,z),Blocks.DARK_OAK_FENCE.defaultBlockState());
        // Exterior glazing continues on the upper floor; lower windows are
        // generated by the shared shell. All entrances remain physically open.
        for(int along:new int[]{3,5,10,12,17,19})for(int y=11;y<=12;y++)for(var at:new BlockPos[]{o.offset(0,y,along),o.offset(22,y,along),o.offset(along,y,0),o.offset(along,y,22)})put(level,clip,at,Blocks.LIGHT_BLUE_STAINED_GLASS.defaultBlockState());
        for(int floor:new int[]{0,8})for(int z:new int[]{4,11,18})for(int x:new int[]{3,19}){
            put(level,clip,o.offset(x,floor+5,z),Blocks.SEA_LANTERN.defaultBlockState());
            put(level,clip,o.offset(x,floor+1,z+1),Blocks.DARK_OAK_PLANKS.defaultBlockState());
            if(floor==0&&x==3)put(level,clip,o.offset(x-1,floor+1,z+1),Blocks.BOOKSHELF.defaultBlockState());
        }
        // Two genuine passage mirrors on the lower floor let a player learn
        // the visual language before the hidden upper vault.
        for(int x:new int[]{7,15})for(int y=1;y<=2;y++)put(level,clip,o.offset(x,y,11),InfiniteContent.ILLUSION_MIRROR.get().defaultBlockState());
    }
    private static void put(WorldGenLevel level,BoundingBox clip,BlockPos at,BlockState state){if(clip.isInside(at)&&level.getBlockEntity(at)==null)level.setBlock(at,state,2);}
    private PorcelainMansionLayout(){}
}
