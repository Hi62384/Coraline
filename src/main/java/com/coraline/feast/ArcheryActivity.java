    static void build(ServerLevel level,BlockPos c){
        if(level.getBlockState(c.below()).is(Blocks.GOLD_BLOCK)){
            // Upgrade ranges generated by older releases without rebuilding the entire arena.
            if(!level.getBlockState(c.offset(26,-1,11)).is(Blocks.BUDDING_AMETHYST))decorate(level,c);
            return;
        }
        for(int x=-27;x<=27;x++)for(int z=-60;z<=12;z++){
            var ground=c.offset(x,-1,z);
            ActivityBlocks.set(level,ground.below(),Blocks.DIRT.defaultBlockState(),2);
            boolean range=z<-7,edge=Math.abs(x)==27||z==-60||z==12;
            boolean lane=range&&Math.floorMod(x+3,6)==0;
            ActivityBlocks.set(level,ground,(edge?Blocks.POLISHED_BLACKSTONE:range?(lane?Blocks.PACKED_MUD:Blocks.GRASS_BLOCK):Blocks.CHERRY_PLANKS).defaultBlockState(),2);
            if(edge)for(int y=1;y<=2;y++)ActivityBlocks.set(level,ground.above(y),Blocks.DARK_OAK_FENCE.defaultBlockState(),2);
        }
        // A visible line marks the boundary; the player is returned to the
        // shooting platform in tick() without putting arrow-blocking glass here.
        for(int x=-25;x<=25;x++)ActivityBlocks.set(level,c.offset(x,-1,-7),Blocks.RED_CONCRETE.defaultBlockState(),2);
        for(int x=-21;x<=21;x+=6){
            ActivityBlocks.set(level,c.offset(x,-1,2),Blocks.POLISHED_DIORITE.defaultBlockState(),2);
            ActivityBlocks.set(level,c.offset(x,-1,3),Blocks.POLISHED_DIORITE.defaultBlockState(),2);
        }
        for(int x:new int[]{-23,23})for(int z:new int[]{-4,8}){
            for(int y=0;y<3;y++)ActivityBlocks.set(level,c.offset(x,y,z),Blocks.DARK_OAK_FENCE.defaultBlockState(),2);
            ActivityBlocks.set(level,c.offset(x,3,z),Blocks.SHROOMLIGHT.defaultBlockState(),2);
        }
        for(int z:new int[]{-18,-29,-40,-51})for(int x=-21;x<=21;x+=6){
            ActivityBlocks.set(level,c.offset(x,-1,z),Blocks.STRIPPED_DARK_OAK_LOG.defaultBlockState(),2);
        }
        decorate(level,c);
        ActivityBlocks.set(level,c.below(),Blocks.GOLD_BLOCK.defaultBlockState(),2);
    }
    private static void decorate(ServerLevel level,BlockPos c){
        // Painted lane inlays and shooting-bay mosaics stay flush with the ground.
        for(int x=-23;x<=23;x++)for(int z=-56;z<=-9;z++){
            if(Math.floorMod(x+3,6)==0){
                ActivityBlocks.set(level,c.offset(x,-1,z),(Math.floorMod(z,8)==0?Blocks.SEA_LANTERN:Blocks.PURPLE_TERRACOTTA).defaultBlockState(),2);
            }else if(Math.floorMod(z+18,11)==0&&Math.floorMod(x+3,6)!=3)
                ActivityBlocks.set(level,c.offset(x,-1,z),Blocks.PINK_TERRACOTTA.defaultBlockState(),2);
        }
        for(int x=-22;x<=22;x++)for(int z=-6;z<=9;z++){
            if(Math.abs(x)==22||z==-6||z==9)ActivityBlocks.set(level,c.offset(x,-1,z),Blocks.MAGENTA_TERRACOTTA.defaultBlockState(),2);
            else if(Math.floorMod(x+3,6)<=1&&z>=1&&z<=5)
                ActivityBlocks.set(level,c.offset(x,-1,z),(z==1||z==5?Blocks.PURPLE_TERRACOTTA:Blocks.PINK_TERRACOTTA).defaultBlockState(),2);
        }
        // Keep raised ornaments outside the seven firing lanes; arrows have an open flight path.
        for(int side:new int[]{-1,1}){
            int edge=side*25;
            for(int z=-55;z<=-9;z++){
                ActivityBlocks.set(level,c.offset(edge,-1,z),(Math.floorMod(z,4)<2?Blocks.PINK_TERRACOTTA:Blocks.MAGENTA_TERRACOTTA).defaultBlockState(),2);
                if(Math.floorMod(z,4)==0)ActivityBlocks.set(level,c.offset(side*24,0,z),Blocks.FLOWERING_AZALEA.defaultBlockState(),2);
                else if(Math.floorMod(z,4)==2)ActivityBlocks.set(level,c.offset(side*24,0,z),Blocks.AZALEA.defaultBlockState(),2);
            }
            for(int z:new int[]{-11,-25,-39,-53}){
                for(int y=0;y<3;y++)ActivityBlocks.set(level,c.offset(edge,y,z),Blocks.CHERRY_FENCE.defaultBlockState(),2);
                ActivityBlocks.set(level,c.offset(edge,3,z),Blocks.SEA_LANTERN.defaultBlockState(),2);
                ActivityBlocks.set(level,c.offset(side*24,0,z-1),Blocks.PINK_TULIP.defaultBlockState(),2);
            }
            for(int x:new int[]{16,24}){
                int at=side*x;
                for(int y=0;y<4;y++)ActivityBlocks.set(level,c.offset(at,y,10),Blocks.STRIPPED_CHERRY_LOG.defaultBlockState(),2);
                ActivityBlocks.set(level,c.offset(at,4,10),Blocks.SEA_LANTERN.defaultBlockState(),2);
            }
            ActivityBlocks.set(level,c.offset(side*21,0,5),com.coraline.registry.ModBlocks.FLOWER_CONSOLE.get().defaultBlockState(),2);
            ActivityBlocks.set(level,c.offset(side*21,0,1),com.coraline.registry.ModBlocks.BRASS_FLOOR_LAMP.get().defaultBlockState(),2);
        }
        // A sheltered return terrace and a floral backstop frame the range without blocking shots.
        for(int x=-24;x<=24;x++)for(int z=8;z<=11;z++)if(Math.floorMod(x,5)==0||z==8||z==11)
            ActivityBlocks.set(level,c.offset(x,5,z),(Math.floorMod(x,2)==0?Blocks.CHERRY_SLAB:Blocks.PINK_STAINED_GLASS).defaultBlockState(),2);
        for(int x=-23;x<=23;x++){
            if(Math.floorMod(x,5)==0){
                ActivityBlocks.set(level,c.offset(x,0,-57),ActivityWorld.persistentLeaves(Blocks.CHERRY_LEAVES),2);
                ActivityBlocks.set(level,c.offset(x,1,-57),ActivityWorld.persistentLeaves(Blocks.FLOWERING_AZALEA_LEAVES),2);
            }
            if(Math.floorMod(x,7)==0)ActivityBlocks.set(level,c.offset(x,-1,-58),Blocks.SEA_LANTERN.defaultBlockState(),2);
        }
        for(int z:new int[]{-14,-36,-58})for(int x=-25;x<=25;x++)if(Math.floorMod(x,5)<=2)
            ActivityBlocks.set(level,c.offset(x,6,z),(Math.floorMod(x,5)==0?Blocks.SEA_LANTERN:Math.floorMod(x,2)==0?Blocks.PINK_STAINED_GLASS:Blocks.MAGENTA_STAINED_GLASS).defaultBlockState(),2);
        for(int x:new int[]{-20,-10,10,20}){
            ActivityBlocks.set(level,c.offset(x,0,7),com.coraline.registry.ModBlocks.ROSE_VELVET_SOFA.get().defaultBlockState(),2);
            ActivityBlocks.set(level,c.offset(x,0,6),com.coraline.registry.ModBlocks.LOW_MARBLE_TABLE.get().defaultBlockState(),2);
        }
        ActivityBlocks.set(level,c.offset(26,-1,11),Blocks.BUDDING_AMETHYST.defaultBlockState(),2);
    }
    static void removeBuild(ServerLevel level,BlockPos c){
        if(!level.getBlockState(c.below()).is(Blocks.GOLD_BLOCK))return;
        for(int x=-27;x<=27;x++)for(int z=-60;z<=12;z++)for(int y=-2;y<=6;y++){
            var at=c.offset(x,y,z);
            if(!level.isEmptyBlock(at))ActivityBlocks.set(level,at,Blocks.AIR.defaultBlockState(),2);
        }
    }
    static void start(ServerPlayer p,VisitData.Scene s,ServerLevel level){
        var c=center(p,s);build(level,c);clean(level,s,c);removeIssued(p);
        s.loop.archeryShotsRemaining=ARROWS;s.loop.archeryIssued=false;
        s.loop.archeryGiftAt=OtherMotherLoop.now(p)+VisitAudio.length(ActivityWorld.introSound(OtherMotherActivities.Activity.ARCHERY_CONTEST));
        ensureFather(p,s,level,c);ensureTargets(p,s,level,c);ensurePlatform(level,s,c);OtherMotherLoop.changed(p);
    }
    static void prepare(ServerPlayer p,VisitData.Scene s,ServerLevel level,BlockPos c){
        LoopProps.hold(level,c);LoopProps.hold(level,c.north(26));LoopProps.hold(level,c.north(49));
        build(level,c);ensureFather(p,s,level,c);ensureTargets(p,s,level,c);ensurePlatform(level,s,c);
    }
    private static void ensureFather(ServerPlayer p,VisitData.Scene s,ServerLevel level,BlockPos c){
        var fathers=level.getEntitiesOfClass(ParentEntity.class,new AABB(c).inflate(10),e->e.getPersistentData().getBoolean("CoralineArcheryFather")&&
            e.getPersistentData().hasUUID(OWNER)&&s.owner.equals(e.getPersistentData().getUUID(OWNER)));
        if(!fathers.isEmpty())return;
        var realm=RealmData.get(p.server).realms.get(s.door);var family=ParentAccess.family(p.server,s.owner);
        var father=ModEntities.DAD.get().create(level);if(father==null)return;
        father.makeOtherParent(family==null?0:Math.max(0,family.dadSkin));father.setNoAi(true);
        father.getPersistentData().putBoolean("CoralineArcheryFather",true);
        father.getPersistentData().putUUID(OWNER,s.owner);father.getPersistentData().putUUID("RealmDoor",s.door);
        father.getPersistentData().putInt("RealmGeneration",realm.parentGeneration);
        father.setPos(c.getX()+3.5,c.getY(),c.getZ()+6.5);father.setYRot(180);father.setYBodyRot(180);
        level.addFreshEntity(father);
    }
    private static void ensureTargets(ServerPlayer p,VisitData.Scene s,ServerLevel level,BlockPos c){
        var current=level.getEntitiesOfClass(ScenePropEntity.class,new AABB(c).inflate(65,8,65),e->isTarget(e)&&
            s.owner.equals(e.owner)&&s.door.equals(e.storyDoor)&&e.getPersistentData().getInt("LoopGeneration")==s.loop.generation);
        for(var target:current){
            float scale=targetScale(target.slot,target.kind());
            if(target.targetScale()!=scale)target.targetScale(scale);
            var data=target.getPersistentData();
            if(!data.getBoolean("ArcheryScaleBase")&&data.contains("ArcheryBaseY")){
                data.putDouble("ArcheryBaseY",data.getDouble("ArcheryBaseY")-1+scale*1.05);
                data.putBoolean("ArcheryScaleBase",true);
            }
        }
        if(current.size()>=TARGETS)return;
        for(int row=0;row<4;row++)for(int lane=0;lane<7;lane++){
            int slot=row*7+lane,x=-18+lane*6,z=-18-row*11;
            int kind=switch(Math.floorMod(lane+row*2,6)){
                case 0->ScenePropEntity.TARGET_STATIC;
                case 1->ScenePropEntity.TARGET_SLIDER;
                case 2->ScenePropEntity.TARGET_BOBBER;
                case 3->ScenePropEntity.TARGET_POPUP;
                case 4->ScenePropEntity.TARGET_SPINNER;
                default->ScenePropEntity.TARGET_GOLD;
            };
            float scale=targetScale(slot,kind);
            var at=Vec3.atBottomCenterOf(c.offset(x,0,z)).add(0,scale*1.05,0);
            boolean present=level.getEntitiesOfClass(ScenePropEntity.class,new AABB(at,at).inflate(2.5,2,2.5),e->isTarget(e)&&e.slot==slot&&s.owner.equals(e.owner)&&e.getPersistentData().getInt("LoopGeneration")==s.loop.generation).size()>0;
            if(present)continue;
            var target=LoopProps.spawn(level,s,kind,at,slot);
            target.targetScale(scale);
            target.getPersistentData().putDouble("ArcheryBaseX",at.x);
            target.getPersistentData().putDouble("ArcheryBaseY",at.y);
            target.getPersistentData().putDouble("ArcheryBaseZ",at.z);
            target.getPersistentData().putBoolean("ArcheryScaleBase",true);
            target.mode(kind==ScenePropEntity.TARGET_POPUP?0:1);
        }
    }
    private static float targetScale(int slot,int kind){
        float scale=1F-Math.min(3,Math.max(0,slot/7))*.22F;
        return kind==ScenePropEntity.TARGET_GOLD?scale*.75F:kind==ScenePropEntity.TARGET_SPINNER?scale*.82F:scale;
    }
    public static void animate(ScenePropEntity target){
        var n=target.getPersistentData();if(!n.contains("ArcheryBaseX"))return;
        double x=n.getDouble("ArcheryBaseX"),y=n.getDouble("ArcheryBaseY"),z=n.getDouble("ArcheryBaseZ");
        double t=target.level().getGameTime()+target.slot*17L;
        int row=Math.min(3,Math.max(0,target.slot/7));
        if(target.kind()==ScenePropEntity.TARGET_SLIDER)x+=Math.sin(t*(.23+row*.045))*(3+row*.7);
        if(target.kind()==ScenePropEntity.TARGET_BOBBER)y+=Math.sin(t*(.24+row*.04))*(2.4+row*.7);
        if(target.kind()==ScenePropEntity.TARGET_POPUP){int open=Math.floorMod((int)t,85)<14?1:0;if(target.mode()!=open)target.mode(open);}
        if(target.kind()==ScenePropEntity.TARGET_GOLD)y+=Math.sin(t*(.08+row*.015))*(.35+row*.1);
        target.setPos(x,y,z);
    }
    static void tick(ServerPlayer p,VisitData.Scene s,BlockPos c){
        if(p.tickCount%20==0){prepare(p,s,p.serverLevel(),c);if(s.loop.archeryIssued)reconcile(p,s);}
        if(!s.loop.archeryIssued&&OtherMotherLoop.now(p)>=s.loop.archeryGiftAt)grant(p,s);
        movePlatform(p,s,c);
        if(s.loop.archeryIssued&&!exitReady(s))return;
        if(p.getZ()<c.getZ()-6||Math.abs(p.getX()-(c.getX()+.5))>25||p.getZ()>c.getZ()+11||p.getY()<78){
            p.teleportTo(p.serverLevel(),c.getX()+.5,c.getY(),c.getZ()+6.5,180,0);
            p.setDeltaMovement(Vec3.ZERO);p.fallDistance=0;
            if(p.tickCount%20==0)p.displayClientMessage(Component.literal("Stay behind the red firing line. Your arrows can cross it."),true);
        }
    }
    private static ScenePropEntity ensurePlatform(ServerLevel level,VisitData.Scene s,BlockPos c){
        var existing=level.getEntitiesOfClass(ScenePropEntity.class,new AABB(c.south(2)).inflate(20,5,4),e->e.kind()==ScenePropEntity.ARCHERY_PLATFORM&&s.owner.equals(e.owner)&&s.loop.generation==e.getPersistentData().getInt("LoopGeneration"));
        if(!existing.isEmpty())return existing.get(0);
        var platform=LoopProps.spawn(level,s,ScenePropEntity.ARCHERY_PLATFORM,new Vec3(c.getX()+.5,c.getY()+.85,c.getZ()+2.5),-1);
        platform.getPersistentData().putUUID(OWNER,s.owner);return platform;
    }
    private static void movePlatform(ServerPlayer p,VisitData.Scene s,BlockPos c){
        var level=p.serverLevel();long time=level.getGameTime();
        // Remove the old integer-stepped block deck from worlds made by older versions.
        if(p.tickCount%20==0)for(int x=-18;x<=18;x++)for(int z=1;z<=3;z++){
            var at=c.offset(x,0,z);if(level.getBlockState(at).is(Blocks.PURPUR_BLOCK))ActivityBlocks.set(level,at,Blocks.AIR.defaultBlockState(),2);
        }
        var platform=ensurePlatform(level,s,c);
        platform.setPos(c.getX()+.5+Math.sin(time*.055)*16,c.getY()+.85,c.getZ()+2.5);
        if(!s.loop.archeryIssued)return;
        if(exitReady(s)){if(p.getVehicle()==platform)p.stopRiding();return;}
        if(p.getVehicle()!=platform){p.stopRiding();p.startRiding(platform,true);p.fallDistance=0;}
    }
    static void clean(ServerLevel level,VisitData.Scene s,BlockPos c){
        var remove=new ArrayList<Entity>();
        for(var e:level.getEntitiesOfClass(Entity.class,new AABB(c).inflate(65,10,65),e->
            (e.getPersistentData().hasUUID(OWNER)&&s.owner.equals(e.getPersistentData().getUUID(OWNER)))||
            (e instanceof ScenePropEntity prop&&(isTarget(prop)||prop.kind()==ScenePropEntity.ARCHERY_PLATFORM)&&s.owner.equals(prop.owner))))remove.add(e);
        remove.forEach(Entity::discard);
    }
    static void removeIssued(ServerPlayer p){
        for(var stack:p.getInventory().items)if(issued(stack))stack.setCount(0);
        for(var stack:p.getInventory().offhand)if(issued(stack))stack.setCount(0);
        p.getInventory().setChanged();
    }
    private static boolean issued(ItemStack stack){return (stack.is(ModItems.ARCHERY_BOW.get())||stack.is(ModItems.ARCHERY_ARROW.get()))&&
        stack.hasTag()&&stack.getTag().getBoolean(ISSUED);}
    private static boolean matches(ItemStack stack,ServerPlayer p,VisitData.Scene s){return issued(stack)&&
        stack.getTag().hasUUID(OWNER)&&p.getUUID().equals(stack.getTag().getUUID(OWNER))&&stack.getTag().getInt(GEN)==s.loop.generation;}
    private static void mark(ItemStack stack,ServerPlayer p,VisitData.Scene s){
        var n=stack.getOrCreateTag();n.putBoolean(ISSUED,true);n.putUUID(OWNER,p.getUUID());n.putInt(GEN,s.loop.generation);
    }
    private static void give(ServerPlayer p,ItemStack stack){p.getInventory().add(stack);if(!stack.isEmpty())p.drop(stack,false);}
    static void grant(ServerPlayer p,VisitData.Scene s){
        if(s.loop.archeryIssued)return;
        removeIssued(p);
        var bow=new ItemStack(ModItems.ARCHERY_BOW.get());mark(bow,p,s);give(p,bow);
        var arrows=new ItemStack(ModItems.ARCHERY_ARROW.get(),ARROWS);mark(arrows,p,s);give(p,arrows);
        s.loop.archeryIssued=true;OtherMotherLoop.changed(p);
        p.serverLevel().playSound(null,p.blockPosition(),SoundEvents.ITEM_PICKUP,SoundSource.PLAYERS,1,1);
        p.sendSystemMessage(Component.literal("Father gives you his contest bow and 64 arrows. Stay on the moving shooting platform; tougher targets earn better prizes."));
    }
    private static void reconcile(ServerPlayer p,VisitData.Scene s){
        int budget=s.loop.archeryShotsRemaining,count=0;boolean hasBow=false;
        for(var stack:p.getInventory().items){if(!matches(stack,p,s))continue;
            if(stack.is(ModItems.ARCHERY_BOW.get()))hasBow=true;
            else if(stack.is(ModItems.ARCHERY_ARROW.get())){int keep=Math.min(stack.getCount(),Math.max(0,budget-count));stack.setCount(keep);count+=keep;}
        }
        for(var stack:p.getInventory().offhand){if(!matches(stack,p,s))continue;
            if(stack.is(ModItems.ARCHERY_BOW.get()))hasBow=true;
            else if(stack.is(ModItems.ARCHERY_ARROW.get())){int keep=Math.min(stack.getCount(),Math.max(0,budget-count));stack.setCount(keep);count+=keep;}
        }
        if(budget>count){var arrows=new ItemStack(ModItems.ARCHERY_ARROW.get(),budget-count);mark(arrows,p,s);give(p,arrows);}
        if(budget>0&&!hasBow){var bow=new ItemStack(ModItems.ARCHERY_BOW.get());mark(bow,p,s);give(p,bow);}
        p.getInventory().setChanged();
    }
    @SubscribeEvent public static void loose(ArrowLooseEvent event){
        if(!(event.getEntity() instanceof ServerPlayer p)||!ActivityWorld.isActivity(p.level()))return;
        var s=OtherMotherLoop.active(p);if(s==null||s.loop.activity!=OtherMotherActivities.Activity.ARCHERY_CONTEST)return;
        var ammo=p.getProjectile(event.getBow());
        if(!s.loop.archeryIssued||s.loop.archeryShotsRemaining<=0||!event.getBow().is(ModItems.ARCHERY_BOW.get())||
            !matches(event.getBow(),p,s)||!matches(ammo,p,s)){
            event.setCanceled(true);p.displayClientMessage(Component.literal("Only Father's issued bow and arrows count in this contest."),true);
        }else if(!(p.getVehicle() instanceof ScenePropEntity platform&&platform.kind()==ScenePropEntity.ARCHERY_PLATFORM&&p.getUUID().equals(platform.owner))){
            event.setCanceled(true);p.displayClientMessage(Component.literal("Stand on the moving platform to shoot."),true);
        }
    }
    @SubscribeEvent public static void arrowSpawn(EntityJoinLevelEvent event){
        if(!(event.getEntity() instanceof AbstractArrow arrow)||!arrow.getPersistentData().getBoolean("CoralineArcheryArrow")||
            !(event.getLevel() instanceof ServerLevel level))return;
        if(!(arrow.getOwner() instanceof ServerPlayer p)||!ActivityWorld.isActivity(level)) {event.setCanceled(true);return;}
        var s=OtherMotherLoop.active(p);var n=arrow.getPersistentData();
        if(n.getBoolean("CoralineArcheryCounted"))return; // Reloading an in-flight arrow is not a second shot.
        if(s==null||s.loop.activity!=OtherMotherActivities.Activity.ARCHERY_CONTEST||!s.loop.archeryIssued||
            s.loop.archeryShotsRemaining<=0||!n.hasUUID(OWNER)||!p.getUUID().equals(n.getUUID(OWNER))||n.getInt(GEN)!=s.loop.generation){event.setCanceled(true);return;}
        arrow.pickup=AbstractArrow.Pickup.DISALLOWED;
        n.putBoolean("CoralineArcheryCounted",true);
        s.loop.archeryShotsRemaining--;OtherMotherLoop.changed(p);
        int left=s.loop.archeryShotsRemaining;
        p.displayClientMessage(Component.literal(left+" contest arrows remaining"),true);
        if(left==0){ActivityWorld.ensureExit(p,s);p.sendSystemMessage(Component.literal("All 64 contest arrows are spent. The return portal has opened behind the firing line."));}
    }
    @SubscribeEvent public static void impact(ProjectileImpactEvent event){
        if(!(event.getProjectile() instanceof AbstractArrow arrow)||!arrow.getPersistentData().getBoolean("CoralineArcheryArrow")||
            !(arrow.getOwner() instanceof ServerPlayer p)||!ActivityWorld.isActivity(p.level()))return;
        if(!(event.getRayTraceResult() instanceof net.minecraft.world.phys.EntityHitResult hit)||
            !(hit.getEntity() instanceof ScenePropEntity target)||!isTarget(target))return;
        event.setImpactResult(ProjectileImpactEvent.ImpactResult.STOP_AT_CURRENT_NO_DAMAGE);arrow.discard();
        var s=OtherMotherLoop.active(p);var n=arrow.getPersistentData();
        if(s==null||s.loop.activity!=OtherMotherActivities.Activity.ARCHERY_CONTEST||!n.getBoolean("CoralineArcheryCounted")||
            !n.hasUUID(OWNER)||!p.getUUID().equals(n.getUUID(OWNER))||n.getInt(GEN)!=s.loop.generation||
            !s.owner.equals(target.owner)||target.getPersistentData().getInt("LoopGeneration")!=s.loop.generation)return;
        double dx=hit.getLocation().x-target.getX(),dy=hit.getLocation().y-(target.getY()+target.getBbHeight()*.5);
        double accuracy=Math.sqrt(dx*dx+dy*dy);
        if(target.kind()==ScenePropEntity.TARGET_POPUP&&target.mode()==0)return;
        if(target.kind()==ScenePropEntity.TARGET_SPINNER){
            double angle=Math.toRadians(target.tickCount*14.0);
            var towardShooter=p.position().subtract(target.position()).normalize();
            Vec3 front=new Vec3(Math.sin(angle),0,Math.cos(angle));
            if(front.dot(towardShooter)<.96)return;
            Vec3 velocity=arrow.getDeltaMovement();double along=velocity.dot(front);
            if(along>=-.15)return;
            double travel=target.position().subtract(hit.getLocation()).dot(front)/along;
            if(Math.abs(travel)>3)return;
            Vec3 crossing=hit.getLocation().add(velocity.scale(travel)).subtract(target.position());
            double across=crossing.x*Math.cos(angle)-crossing.z*Math.sin(angle);
            if(Math.abs(across)>.40*target.targetScale()||Math.abs(crossing.y-target.getBbHeight()*.5)>.40*target.targetScale())return;
        }
        int row=Math.min(3,Math.max(0,target.slot/7));
        int tier=Math.min(3,row+(target.kind()==ScenePropEntity.TARGET_STATIC?0:1));
        boolean bullseye=accuracy<.11*target.targetScale();
        if(bullseye)tier=Math.min(3,tier+1);
        var reward=reward(p,tier);String name=reward.getHoverName().getString();give(p,reward);
        p.serverLevel().playSound(null,target.blockPosition(),SoundEvents.ARROW_HIT_PLAYER,SoundSource.PLAYERS,.8F,1.1F+tier*.13F);
        p.sendSystemMessage(Component.literal((bullseye?"Bullseye! ":"Hit! ")+"Tier "+(tier+1)+" prize: "+name+"."));
    }
